"""Tab completion for zsh, bash and PowerShell, generated from the CLI definition itself.

The script is written once to the data directory and loaded by one marked line in
the shell profile, so opening a terminal never runs Python.
"""

import argparse
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

from ai_handoff import paths
from ai_handoff.integrations.files import Session

SHELLS = ("zsh", "bash", "powershell")
EXTENSIONS = {"zsh": "zsh", "bash": "bash", "powershell": "ps1"}
PROFILE_MARKER = "# handoff completion (added by the Handoff installer)"
HIDDEN_COMMANDS = ("hook", "serve")


@dataclass(frozen=True)
class Option:
    flags: tuple[str, ...]
    description: str
    takes_value: bool
    choices: tuple[str, ...]
    is_path: bool


@dataclass(frozen=True)
class Command:
    name: str
    description: str
    options: tuple[Option, ...]
    values: tuple[str, ...] = ()  # choices of a positional argument (e.g. the shell names)


def commands(parser: argparse.ArgumentParser) -> list[Command]:
    """Public commands and their options, read from the argparse definition."""
    from ai_handoff.i18n import t

    subparsers = next(action for action in parser._actions if isinstance(action, argparse._SubParsersAction))
    result = []
    for name, subparser in subparsers.choices.items():
        if name in HIDDEN_COMMANDS:
            continue
        options = []
        values: tuple[str, ...] = ()
        for action in subparser._actions:
            choices = action.choices if isinstance(action.choices, (list, tuple)) else ()
            if not action.option_strings:
                values += tuple(str(choice) for choice in choices)
                continue
            options.append(
                Option(
                    flags=tuple(action.option_strings),
                    description=action.help or "",
                    takes_value=action.nargs != 0,
                    choices=tuple(str(choice) for choice in choices),
                    is_path=action.dest == "path",
                )
            )
        result.append(Command(name, t(f"cmd.{name}"), tuple(options), values))
    return result


# Script generators


def _zsh_quote(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def _zsh_description(text: str) -> str:
    return text.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


def zsh_script(items: list[Command]) -> str:
    lines = [
        "#compdef handoff",
        "# Generated by Handoff: zsh completion for the handoff command.",
        "_handoff() {",
        '  local curcontext="$curcontext" state line',
        "  typeset -A opt_args",
        "  local -a commands",
        "  commands=(",
        *(f"    {_zsh_quote(item.name + ':' + item.description)}" for item in items),
        "  )",
        "  _arguments -C '1: :->command' '*:: :->args'",
        "  case $state in",
        "    (command) _describe -t commands 'handoff command' commands ;;",
        "    (args)",
        "      case $line[1] in",
    ]
    for item in items:
        specs = []
        for option in item.options:
            description = _zsh_description(option.description)
            if option.is_path:
                action = ":directory:_files -/"
            elif option.choices:
                action = f":value:({' '.join(option.choices)})"
            elif option.takes_value:
                action = ":value: "
            else:
                action = ""
            exclusive = f"({' '.join(option.flags)})" if len(option.flags) > 1 else ""
            flags = "{" + ",".join(option.flags) + "}" if len(option.flags) > 1 else option.flags[0]
            if len(option.flags) > 1:
                specs.append(f"{_zsh_quote(exclusive)}{flags}{_zsh_quote(f'[{description}]{action}')}")
            else:
                specs.append(_zsh_quote(f"{flags}[{description}]{action}"))
        if item.values:
            specs.append(_zsh_quote(f"1:value:({' '.join(item.values)})"))
        body = " \\\n            ".join(specs) if specs else ""
        lines.append(
            f"        ({item.name}) _arguments -s {body} ;;" if body else f"        ({item.name}) ;;"
        )
    lines += [
        "      esac ;;",
        "  esac",
        "}",
        "# A default macOS zsh does not load the completion system: load it when it is missing.",
        "if (( ! $+functions[compdef] )); then",
        "  autoload -Uz compinit && compinit -i",
        "fi",
        "compdef _handoff handoff",
        "",
    ]
    return "\n".join(lines)


def bash_script(items: list[Command]) -> str:
    names = " ".join(item.name for item in items)
    lines = [
        "# Generated by Handoff: bash completion for the handoff command.",
        "_handoff() {",
        '  local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD-1]}" options=""',
        '  if [ "$COMP_CWORD" -eq 1 ]; then',
        f'    COMPREPLY=( $(compgen -W "{names}" -- "$cur") )',
        "    return",
        "  fi",
        '  case "$prev" in',
    ]
    value_cases: dict[str, str] = {}
    for item in items:
        for option in item.options:
            if option.is_path:
                action = 'COMPREPLY=( $(compgen -d -- "$cur") ); return ;;'
            elif option.choices:
                action = f'COMPREPLY=( $(compgen -W "{" ".join(option.choices)}" -- "$cur") ); return ;;'
            elif option.takes_value:
                action = "COMPREPLY=(); return ;;"
            else:
                continue
            for flag in option.flags:
                value_cases.setdefault(flag, action)
    lines += [f"    {flag}) {action}" for flag, action in value_cases.items()]
    lines += ["  esac", '  case "${COMP_WORDS[1]}" in']
    for item in items:
        words = " ".join([*item.values, *(flag for option in item.options for flag in option.flags)])
        lines.append(f'    {item.name}) options="{words}" ;;')
    lines += [
        "  esac",
        '  COMPREPLY=( $(compgen -W "$options" -- "$cur") )',
        "}",
        "complete -F _handoff handoff",
        "",
    ]
    return "\n".join(lines)


def _ps_quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def powershell_script(items: list[Command]) -> str:
    command_entries = "; ".join(f"{_ps_quote(item.name)} = {_ps_quote(item.description)}" for item in items)
    option_entries = []
    values: dict[str, tuple[str, ...]] = {}
    for item in items:
        flags = [f"@({_ps_quote(value)}, {_ps_quote(value)})" for value in item.values]
        for option in item.options:
            flags += [f"@({_ps_quote(flag)}, {_ps_quote(option.description)})" for flag in option.flags]
            if option.choices:
                for flag in option.flags:
                    values.setdefault(flag, option.choices)
        option_entries.append(f"        {_ps_quote(item.name)} = @({', '.join(flags)})")
    value_entries = "; ".join(
        f"{_ps_quote(flag)} = @({', '.join(_ps_quote(choice) for choice in choices)})"
        for flag, choices in values.items()
    )
    return "\n".join(
        [
            "# Generated by Handoff: PowerShell completion for the handoff command.",
            "Register-ArgumentCompleter -Native -CommandName handoff -ScriptBlock {",
            "    param($wordToComplete, $commandAst, $cursorPosition)",
            f"    $commands = [ordered]@{{ {command_entries} }}",
            "    $options = @{",
            *option_entries,
            "    }",
            f"    $values = @{{ {value_entries} }}",
            "    $words = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })",
            "    $position = if ($wordToComplete) { $words.Count - 1 } else { $words.Count }",
            "    $results = @()",
            "    if ($position -le 1) {",
            "        foreach ($name in $commands.Keys) {",
            '            if ($name -like "$wordToComplete*") { $results += ,@($name, $commands[$name]) }',
            "        }",
            "    } else {",
            "        $previous = $words[$position - 1]",
            "        if ($values.ContainsKey($previous)) {",
            "            foreach ($value in $values[$previous]) {",
            '                if ($value -like "$wordToComplete*") { $results += ,@($value, $value) }',
            "            }",
            "        } elseif ($options.ContainsKey($words[1])) {",
            "            foreach ($option in $options[$words[1]]) {",
            '                if ($option[0] -like "$wordToComplete*") {',
            "                    $results += ,@($option[0], $option[1])",
            "                }",
            "            }",
            "        }",
            "    }",
            "    foreach ($result in $results) {",
            "        $tip = if ($result[1]) { $result[1] } else { $result[0] }",
            "        $kind = [System.Management.Automation.CompletionResultType]::ParameterValue",
            "        $text = $result[0]",
            "        [System.Management.Automation.CompletionResult]::new($text, $text, $kind, $tip)",
            "    }",
            "}",
            "",
        ]
    )


GENERATORS = {"zsh": zsh_script, "bash": bash_script, "powershell": powershell_script}


def script(shell: str, parser: argparse.ArgumentParser) -> str:
    return GENERATORS[shell](commands(parser))


# Installation in the shell profile


def detect_shell() -> str | None:
    if sys.platform == "win32":
        return "powershell"
    name = Path(os.environ.get("SHELL", "")).name
    return name if name in ("zsh", "bash") else None


def script_path(shell: str) -> Path:
    return paths.data_dir() / "completion" / f"handoff.{EXTENSIONS[shell]}"


def profile_path(shell: str) -> Path | None:
    home = Path.home()
    if shell == "zsh":
        return Path(os.environ.get("ZDOTDIR") or home) / ".zshrc"
    if shell == "bash":
        return home / (".bash_profile" if sys.platform == "darwin" else ".bashrc")
    for executable in ("pwsh", "powershell"):
        found = shutil.which(executable)
        if not found:
            continue
        try:
            result = subprocess.run(
                [found, "-NoProfile", "-NonInteractive", "-Command", "$PROFILE.CurrentUserCurrentHost"],
                capture_output=True,
                text=True,
                timeout=30,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if result.returncode == 0 and result.stdout.strip():
            return Path(result.stdout.strip())
    return None


def profile_line(shell: str) -> str:
    target = script_path(shell)
    if shell == "powershell":
        quoted = _ps_quote(str(target))
        return f"if (Test-Path {quoted}) {{ . {quoted} }}  {PROFILE_MARKER}"
    quoted = '"' + str(target).replace('"', '\\"') + '"'
    return f"[ -f {quoted} ] && . {quoted}  {PROFILE_MARKER}"


def _without_our_line(text: str) -> str:
    return "".join(line for line in text.splitlines(keepends=True) if PROFILE_MARKER not in line)


def installed(shell: str) -> bool:
    profile = profile_path(shell)
    try:
        return profile is not None and PROFILE_MARKER in profile.read_text(encoding="utf-8")
    except OSError:
        return False


def install(shell: str, parser: argparse.ArgumentParser, session: Session) -> Path:
    profile = profile_path(shell)
    if profile is None:
        raise FileNotFoundError(shell)
    session.write_text(script_path(shell), script(shell, parser), f"{script_path(shell)}: completion script")
    current = profile.read_text(encoding="utf-8") if profile.exists() else ""
    kept = _without_our_line(current)
    separator = "" if not kept or kept.endswith("\n") else "\n"
    session.write_text(profile, f"{kept}{separator}{profile_line(shell)}\n", f"{profile}: completion")
    return profile


def refresh(parser: argparse.ArgumentParser) -> list[str]:
    """Regenerate the scripts of every shell where completion is installed (after an upgrade)."""
    session = Session()
    for shell in SHELLS:
        if script_path(shell).exists():
            session.write_text(script_path(shell), script(shell, parser), f"{shell} completion")
    return session.changes


def uninstall(session: Session) -> None:
    for shell in SHELLS:
        profile = profile_path(shell) if shell != "powershell" or script_path(shell).exists() else None
        if profile is not None and profile.exists():
            current = profile.read_text(encoding="utf-8")
            if PROFILE_MARKER in current:
                session.write_text(profile, _without_our_line(current), f"{profile}: removed completion")
        session.delete(script_path(shell), f"{script_path(shell)}: deleted")
