def claude_desktop_config() -> Path:
    return app_support() / "Claude" / "claude_desktop_config.json"


def vscode_user_dir() -> Path:
    return app_support() / "Code" / "User"


def zed_dir() -> Path:
    return appdata() / "Zed" if sys.platform == "win32" else home() / ".config" / "zed"


def windsurf_parts() -> list[Part]:
    parts: list[Part] = []
    legacy = home() / ".codeium" / "windsurf"
    devin = (appdata() if sys.platform == "win32" else home() / ".config") / "devin"
    for folder in (legacy, devin):
        if folder.exists():
            parts.append(JsonEntry(folder / "mcp_config.json", ("mcpServers",), stdio_entry()))
    parts.append(MarkdownBlock(legacy / "memories" / "global_rules.md", instructions))
    return parts


